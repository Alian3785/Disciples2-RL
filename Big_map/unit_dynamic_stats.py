def apply_dynamic_stat_growth(unit, next_level):
    """Apply original increments; keep campaign snapshots in sync for battle save."""
    profile = DYNAMIC_STAT_PROFILES.get(dynamic_unit_id(unit))
    if profile is None:
        return False
    threshold, early, late, primary, secondary, secondary_power = profile
    hp, damage, heal, armor, power, initiative = early if next_level <= threshold else late
    increments = {
        'damage': damage if primary == 1 else heal if primary == 2 else 0,
        'damage_secondary': damage if secondary == 1 else heal if secondary == 2 else 0,
        'armor': armor,
        'accuracy': power,
        'accuracy_secondary': power if secondary_power else 0,
        'initiative': initiative,
        'max_health': hp,
    }
    old_max = float(unit.get('max_health', unit.get('maxhp', 0)) or 0)
    old_hp = float(unit.get('health', unit.get('hp', 0)) or 0)
    for stat, increment in increments.items():
        if not increment:
            continue
        keys = {stat}
        keys.update(k for k in unit if k.startswith('campaign_') and k.endswith('_base_' + stat))
        if stat == 'damage':
            keys.update(k for k in ('original_damage', 'lower_damage_original_damage') if k in unit)
        elif stat == 'armor':
            keys.update(k for k in ('base_armor', 'shatter_original_armor') if k in unit)
        elif stat == 'initiative':
            keys.add('initiative_base')
        previous = unit.get(stat, 0)
        for key in keys:
            value = max(0, int(unit.get(key, previous) or 0) + increment)
            unit[key] = min(100, value) if stat.startswith('accuracy') else value
    unit['original_damage'] = unit.get('original_damage', unit.get('damage', 0))
    # Preserve injuries when the maximum increases, without reviving dead units.
    if old_max > 0:
        unit['health'] = min(unit['max_health'], int(old_hp * unit['max_health'] / old_max + 0.5))
    if 'hp' in unit:
        unit['hp'] = unit.get('health', 0)
    if 'maxhp' in unit:
        unit['maxhp'] = unit.get('max_health', 0)
    return True
